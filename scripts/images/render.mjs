#!/usr/bin/env node
// Renders the README images into assets/ as SVG + PNG.
//   node scripts/images/render.mjs [--bench <file.json>]
// Numbers come from src/ at render time. The performance chart is drawn only when --bench is given.
import { mkdirSync, writeFileSync } from "fs";
import { join, resolve } from "path";
import assert from "assert/strict";
import { root } from "../lib/fs-scan.mjs";
import { loadStats, loadBench } from "./data.mjs";
import { findRenderer, rasterize } from "./rasterize.mjs";
import { heroSvg, HERO } from "./hero.mjs";
import { architectureSvg, ARCH } from "./architecture.mjs";
import { coverageSvg, COVERAGE } from "./coverage.mjs";
import { performanceSvg, PERF } from "./performance.mjs";
import { cliSvg, CLI } from "./cli.mjs";

function parseArgs(argv) {
  const args = { bench: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--bench") {
      args.bench = argv[++i];
      if (!args.bench) throw new Error("--bench needs a file path");
    } else if (argv[i].startsWith("--bench=")) {
      args.bench = argv[i].slice("--bench=".length);
    } else if (argv[i] === "--help" || argv[i] === "-h") {
      console.log("Usage: node scripts/images/render.mjs [--bench <file.json>]");
      process.exit(0);
    } else {
      throw new Error(`unknown argument: ${argv[i]}`);
    }
  }
  return args;
}

// Self-check on every output: accessible name, no emoji, no tool-vendor branding.
const BANNED = /claude|anthropic|generated by|openai|chatgpt|copilot/i;
const EMOJI = /\p{Extended_Pictographic}/u;
function check(name, svg) {
  assert.match(svg, /<title id="[^"]+">[^<]+<\/title>/, `${name}: missing <title>`);
  assert.match(svg, /<desc id="[^"]+">[^<]+<\/desc>/, `${name}: missing <desc>`);
  assert.doesNotMatch(svg, EMOJI, `${name}: contains an emoji`);
  assert.doesNotMatch(svg, BANNED, `${name}: contains banned branding text`);
  assert.doesNotMatch(svg, /NaN|undefined|Infinity/, `${name}: contains a broken number`);
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const stats = loadStats();
  const bench = args.bench ? loadBench(resolve(process.cwd(), args.bench)) : null;

  const jobs = [
    ["hero", HERO, heroSvg(stats)],
    ["architecture", ARCH, architectureSvg(stats)],
    ["coverage", COVERAGE, coverageSvg(stats)],
    ["cli", CLI, cliSvg(stats)],
  ];
  if (bench) jobs.push(["performance", PERF, performanceSvg(bench)]);
  else console.log("skip  performance (pass --bench <file> to draw it)");

  const outDir = join(root, "assets");
  mkdirSync(outDir, { recursive: true });
  for (const [name, , svg] of jobs) {
    check(name, svg);
    writeFileSync(join(outDir, `${name}.svg`), svg);
  }

  const renderer = findRenderer();
  for (const [name, { w, h }, svg] of jobs) {
    const png = join(outDir, `${name}.png`);
    rasterize(renderer, svg, w, h, png);
    console.log(`wrote assets/${name}.svg  assets/${name}.png  (${w}x${h}, ${renderer.kind})`);
  }
}

try {
  main();
} catch (err) {
  console.error(`render: ${err instanceof Error ? err.message : err}`);
  process.exit(1);
}
